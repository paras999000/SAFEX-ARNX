export function getSavedLanguage() {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (saved && (saved === 'en' || saved === 'hi' || saved === 'sat')) {
      return saved;
    }
  } catch (e) {
    console.warn('[SAFEX i18n] Storage access error:', e);
  }
  return 'en';
}

export function saveLanguage(lang) {
  try {
    if (lang === 'en' || lang === 'hi' || lang === 'sat') {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
    }
  } catch (e) {
    console.warn('[SAFEX i18n] Storage write error:', e);
  }
}

let activeLang = getSavedLanguage();

export function setGlobalLanguage(lang) {
  if (lang === 'en' || lang === 'hi' || lang === 'sat') {
    activeLang = lang;
    saveLanguage(lang);
  }
}

export function getGlobalLanguage() {
  return activeLang;
}

export function t(key, params = {}) {
  const lang = activeLang || 'en';
  const dict = translations[lang] || translations.en;
  let text = dict[key] !== undefined ? dict[key] : (translations.en[key] !== undefined ? translations.en[key] : key);
  
  if (params && typeof params === 'object') {
    Object.keys(params).forEach(k => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), params[k]);
    });
  }
  return text;
}
